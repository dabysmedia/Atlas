import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync } from 'node:fs';
import sharp from 'sharp';
const base = process.env.BASE_URL ?? 'http://localhost:3005', shots = 'shots/hex-dossiers';
mkdirSync(shots, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } }), page = await context.newPage();
page.setDefaultTimeout(30000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
const api = (url, method = 'GET', body) => page.evaluate(async ({ url, method, body }) => {
  const r = await fetch(url, { method, ...(body === undefined ? {} : { headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }) });
  const value = await r.json(); if (!r.ok) throw Error(JSON.stringify(value)); return value;
}, { url, method, body });
const login = async (p, username = 'gm', password = process.env.ATLAS_PASS ?? 'atlas-local-playtest') => {
  await p.goto(base); await p.locator('#u').fill(username); await p.locator('#p').fill(password);
  await p.getByRole('button', { name: 'Sign in', exact: true }).click(); await p.waitForSelector('canvas.map');
};
let world, playerContext;
try {
  await login(page);
  world = await api('/api/worlds', 'POST', { name: `Hex dossier QA ${Date.now()}`, cols: 16, rows: 12 });
  const path = `/api/worlds/${world.id}`, initial = await api(`${path}/map`), hex = initial.hexes.find(h => h.q === 7 && h.r === 4);
  await api(`${path}/hexes/${hex.id}`, 'PATCH', { name: 'QA Overlook', notes: 'QA secret: private to the GM.' });
  const faction = await api(`${path}/factions`, 'POST', { name: 'QA Company', color: '#78b9ad' });
  await api(`${path}/tokens`, 'POST', { name: 'QA Ruins', kind: 'ruins', hexId: hex.id, factionId: faction.id });
  await api(`${path}/tokens`, 'POST', { name: 'QA Village', kind: 'village', hexId: hex.id, factionId: faction.id });
  await api(`${path}/tokens`, 'POST', { name: 'QA Scout', kind: 'unit', hexId: hex.id, factionId: faction.id });
  const campaign = await api(`${path}/campaigns`, 'POST', { name: 'QA expedition' });
  const username = `hex-qa-${Date.now()}`;
  await api(`${path}/players`, 'POST', { username, password: 'hex-qa-password', factionId: faction.id, campaignId: campaign.id });
  await api(`${path}/campaigns/${campaign.id}/fog`, 'POST', { hexIds: [hex.id], explored: true });
  const before = await api(`${path}/map`);
  await page.goto(`${base}/w/${world.id}/map?focus=hex:${hex.id}`); await page.waitForFunction(() => window.__atlasMap?.hasGround);
  const panel = page.locator('.hex-dossier'); await panel.getByRole('button', { name: 'Edit hex details', exact: true }).waitFor();
  assert.equal(await panel.locator('input,textarea,select').count(), 0, 'read view has no editors');
  assert.match(await panel.innerText(), /No resources recorded/);
  await page.evaluate(() => window.__atlasBeforeDetails = window.__atlasMap);
  await panel.getByRole('button', { name: 'Edit hex details', exact: true }).click();
  const lore = 'User-authored QA lore: a place remembered by the company.\n\nA second paragraph with an unresolved detail, still unresolved.';
  await panel.getByLabel('Hex lore', { exact: true }).fill(lore);
  const art = await sharp(readFileSync('server/assets/demo-map.webp')).resize(900, 700, { fit: 'cover' }).png().toBuffer();
  await panel.getByLabel('Upload hex artwork', { exact: true }).setInputFiles({ name: 'QA-overlook.png', mimeType: 'image/png', buffer: art });
  await panel.getByLabel('Artwork vertical position', { exact: true }).waitFor();
  await panel.getByRole('button', { name: 'Add hex resource', exact: true }).click();
  await panel.getByLabel('Resource name', { exact: true }).fill('QA mineral deposit');
  await panel.getByLabel('Resource kind', { exact: true }).selectOption('mineral');
  await panel.getByLabel('Resource availability', { exact: true }).fill('Unresolved — not surveyed');
  await panel.getByLabel('Resource notes', { exact: true }).fill('User-authored resource description.');
  await panel.getByRole('button', { name: 'Save details', exact: true }).click();
  await panel.getByRole('button', { name: 'Edit hex details', exact: true }).waitFor();
  await panel.locator('.hex-dossier-body').evaluate(el => el.scrollTop = 0);
  await page.screenshot({ path: `${shots}/read.png` });
  assert.equal(await panel.locator('input,textarea,select').count(), 0);
  assert.equal(await page.evaluate(() => window.__atlasMap === window.__atlasBeforeDetails), true);
  const endpoint = `${path}/hexes/${hex.id}/presentation`, saved = await api(endpoint);
  assert.equal(saved.lore, lore); assert.equal(saved.resources.length, 1); assert(saved.heroId);
  assert.deepEqual((await api(`${path}/map`)).hexes, before.hexes);
  // A second save exercises the persisted response shape, not only the empty initial profile.
  await panel.getByRole('button', { name: 'Edit hex details', exact: true }).click();
  await panel.getByLabel('Hex lore', { exact: true }).fill(lore + '\nSaved twice.');
  await panel.getByRole('button', { name: 'Save details', exact: true }).click();
  await panel.getByRole('button', { name: 'Edit hex details', exact: true }).waitFor();
  await panel.getByRole('button', { name: 'Edit hex details', exact: true }).click();
  await panel.getByLabel('Hex name', { exact: true }).fill('Discard this draft');
  await panel.getByLabel('Hex lore', { exact: true }).fill('Discard this lore');
  await panel.getByRole('button', { name: 'Place a marker', exact: true }).click();
  const markerDialog = page.getByRole('dialog', { name: 'Place a marker', exact: true });
  await markerDialog.getByRole('button', { name: 'Camp', exact: true }).click();
  await markerDialog.getByPlaceholder('Name', { exact: true }).fill('QA Camp');
  await markerDialog.getByRole('button', { name: 'Place', exact: true }).click();
  await panel.getByLabel('Hex lore', { exact: true }).waitFor();
  assert.equal(await panel.getByLabel('Hex lore', { exact: true }).inputValue(), 'Discard this lore', 'Adding a POI preserves the hex draft');
  await panel.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.match(await panel.locator('h2').innerText(), /QA Overlook/);
  assert.equal((await api(endpoint)).lore, lore + '\nSaved twice.');
  await panel.getByRole('button', { name: 'Edit hex details', exact: true }).click();
  await panel.getByLabel('Hex lore', { exact: true }).fill('Keep my draft');
  const current = await api(endpoint);
  await api(endpoint, 'PATCH', { revision: current.revision, heroId: current.heroId, heroFocus: current.heroFocus, lore: current.lore + '\nOther screen.', resources: current.resources });
  await panel.getByRole('alert').filter({ hasText: 'changed on another screen' }).waitFor();
  assert.equal(await panel.getByRole('button', { name: 'Save details', exact: true }).isDisabled(), true);
  await panel.getByRole('button', { name: 'Cancel', exact: true }).click();
  await panel.locator('.hex-lore').filter({ hasText: 'Other screen.' }).waitFor();
  // Reload, then exercise card navigation and a phone's reading area.
  await page.goto(`${base}/w/${world.id}/map?focus=hex:${hex.id}`); await panel.locator('.hex-lore').waitFor();
  await panel.locator('.hex-hero-image').waitFor();
  await panel.locator('.hex-resource').scrollIntoViewIfNeeded(); await page.screenshot({ path: `${shots}/resources.png` });
  await panel.getByRole('button', { name: /QA Ruins/ }).click();
  await page.getByLabel('Marker name', { exact: true }).waitFor();
  await page.goto(`${base}/w/${world.id}/map?focus=hex:${hex.id}`); await panel.locator('.hex-lore').waitFor();
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(600);
  await page.screenshot({ path: `${shots}/mobile.png` });
  const b = await panel.boundingBox(); assert(b.x >= 0 && b.x + b.width <= 391);
  assert(await panel.locator('.hex-dossier-body').evaluate(el => el.clientHeight) > 150);
  playerContext = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const player = await playerContext.newPage(); player.on('pageerror', e => errors.push(e.message));
  await login(player, username, 'hex-qa-password');
  await player.goto(`${base}/w/${world.id}/map?focus=hex:${hex.id}`);
  const playerPanel = player.locator('.hex-dossier'); await playerPanel.locator('.hex-lore').waitFor();
  assert.equal(await playerPanel.getByRole('button', { name: 'Edit hex details', exact: true }).count(), 0);
  assert(!/QA secret/.test(await playerPanel.innerText()));
  assert.equal(await playerPanel.locator('input,textarea,select').count(), 0);
  await player.screenshot({ path: `${shots}/player.png` });
  assert.deepEqual(errors, []); assert.deepEqual((await api(`${path}/map`)).hexes, before.hexes);
  console.log('PASS: read-first immersive hex panel, hero upload, lore/resources, second save, cancel, conflict/live refresh, POI navigation, reload persistence, mobile/player views, unchanged hex data and retained renderer');
} finally {
  if (world) await api(`/api/worlds/${world.id}`, 'DELETE').catch(() => {});
  await playerContext?.close(); await browser.close();
}
